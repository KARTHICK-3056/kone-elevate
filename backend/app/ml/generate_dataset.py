"""Synthetic elevator-component degradation dataset generator.

WHY SYNTHETIC DATA
------------------
No real KONE service, inspection, sensor or removal records are available to
this project. Rather than fabricate a claim of real data, the prototype
generates a *transparently documented* synthetic dataset with realistic,
correlated degradation physics.

GENERATIVE MODEL
----------------
The generator is a small causal simulator rather than a random-number dump:

    building traffic (duty)  ->  operating hours / load cycles
    maintenance quality      ->  service count / service interval
    age x duty x load        ->  latent WEAR  (the hidden true condition)
    latent WEAR              ->  vibration, temperature, inspection score,
                                 repairs, failures  (all NOISY observations)
    latent WEAR + decision flow -> recommendation category

Two properties matter for honest ML:

1. **No target leakage.** ``health_score`` is never a model feature; the label
   is generated from the *latent* wear variable, which the model never sees.
2. **Deliberate class overlap.** Every observation is a noisy view of the
   latent wear, plus a small share of label noise. A Random Forest therefore
   lands in a realistic accuracy band instead of an implausible 100%.

Run directly:  ``python -m app.ml.generate_dataset --records 10000``
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Dict, List, Optional, Tuple

import numpy as np
import pandas as pd

from app.ml import decision_flow
from app.ml.features import FEATURE_COLUMNS, TARGET_COLUMN, reference_for
from app.utils.enums import ComponentType, Recommendation

# --------------------------------------------------------------------------
# Population structure
# --------------------------------------------------------------------------
#: Relative frequency of each component type in a modernisation portfolio.
TYPE_WEIGHTS: Dict[str, float] = {
    "Motor": 0.14,
    "Steel Rope": 0.16,
    "Brake": 0.11,
    "Governor": 0.08,
    "Door Operator": 0.15,
    "Sheave": 0.11,
}

#: Plausible material mix for each component type.
TYPE_MATERIALS: Dict[str, List[Tuple[str, float]]] = {
    "Motor": [("Steel", 0.62), ("Copper", 0.30), ("Aluminum", 0.08)],
    "Steel Rope": [("Steel", 1.0)],
    "Brake": [("Cast Iron", 0.55), ("Steel", 0.38), ("Composite", 0.07)],
    "Governor": [("Cast Iron", 0.48), ("Steel", 0.47), ("Aluminum", 0.05)],
    "Door Operator": [("Aluminum", 0.44), ("Steel", 0.36), ("Composite", 0.20)],
    "Sheave": [("Cast Iron", 0.63), ("Steel", 0.37)],
}

#: Additive wear offsets applied when converting latent wear into a label.
#: Positive values make the policy stricter (earlier retirement).
SAFETY_STRICTNESS = 0.065          # steel ropes, brakes, governors
STRUCTURAL_LENIENCY = -0.055       # sheaves tolerate more wear

#: Latent-wear thresholds of the decision flow: (no longer suitable for the
#: current application, sub-components no longer serviceable).
WEAR_THRESHOLDS = (0.35, 0.56)

SAFETY_CRITICAL = {"Steel Rope", "Brake", "Governor"}
STRUCTURAL = {"Sheave"}

DATASET_NOTICE = (
    "SYNTHETIC DATA - generated by app.ml.generate_dataset. Not derived from "
    "any real KONE service, inspection or removal record."
)


# --------------------------------------------------------------------------
# Helpers
# --------------------------------------------------------------------------
def _weighted_choice(rng: np.random.Generator, options: List[Tuple[str, float]], size: int) -> np.ndarray:
    labels = [name for name, _ in options]
    probs = np.array([weight for _, weight in options], dtype=float)
    probs = probs / probs.sum()
    return rng.choice(labels, size=size, p=probs)


def _effective_wear(wear: float, component_type: str, material: str) -> float:
    """Latent wear with the type/material policy offsets applied."""
    effective = wear
    if component_type in SAFETY_CRITICAL:
        effective += SAFETY_STRICTNESS
    if component_type in STRUCTURAL:
        effective += STRUCTURAL_LENIENCY
    return effective


def _label_from_wear(wear: float, component_type: str, material: str) -> str:
    """Apply the four-gate decision flow to a latent wear value.

    Delegates to ``decision_flow.label_from_wear`` so the training labels and
    the live recommendation follow the same policy: continue using while the
    part is suitable for its current application; otherwise recover
    sub-components while they are still serviceable (only for types that have
    separable sub-components); otherwise recover material where the material
    allows it; otherwise dispose.
    """
    return decision_flow.label_from_wear(
        _effective_wear(wear, component_type, material),
        component_type,
        material,
        (WEAR_THRESHOLDS[0], WEAR_THRESHOLDS[1]),
    )


_ORDER = [
    Recommendation.CONTINUE_USING.value,
    Recommendation.COMPONENT_RECOVERY.value,
    Recommendation.MATERIAL_RECOVERY.value,
    Recommendation.DISPOSE.value,
]


def _feasible_labels(component_type: str, material: str) -> List[str]:
    """The categories the decision flow can reach for this type and material, in order."""
    labels = [Recommendation.CONTINUE_USING.value]
    if decision_flow.HAS_SEPARABLE_SUBCOMPONENTS.get(component_type, False):
        labels.append(Recommendation.COMPONENT_RECOVERY.value)
    if material in decision_flow.RECOVERABLE_MATERIALS:
        labels.append(Recommendation.MATERIAL_RECOVERY.value)
    else:
        labels.append(Recommendation.DISPOSE.value)
    return labels


def _apply_label_noise(
    rng: np.random.Generator,
    labels: np.ndarray,
    flip_probability: float,
    component_types: np.ndarray,
    materials: np.ndarray,
) -> np.ndarray:
    """Move a small share of labels to an adjacent *feasible* class.

    Real engineering dispositions are not perfectly consistent between
    inspectors, sites and years. Modelling that as adjacent-class noise keeps
    the achievable accuracy realistic. The flip stays within the categories
    the flow can reach for that row - a steel rope is never labelled
    Component Recovery, and a steel part never Dispose, by noise alone.
    """
    if flip_probability <= 0:
        return labels
    flip = rng.random(len(labels)) < flip_probability
    direction = rng.choice([-1, 1], size=len(labels))
    out = labels.copy()
    for i in np.flatnonzero(flip):
        feasible = _feasible_labels(str(component_types[i]), str(materials[i]))
        position = feasible.index(labels[i])
        out[i] = feasible[int(np.clip(position + direction[i], 0, len(feasible) - 1))]
    return out


# --------------------------------------------------------------------------
# Generator
# --------------------------------------------------------------------------
def generate_dataset(
    n_records: int = 10_000,
    seed: int = 42,
    component_types: Optional[List[str]] = None,
    noise_level: float = 1.0,
    include_latent: bool = False,
) -> pd.DataFrame:
    """Generate a correlated synthetic degradation dataset.

    Parameters
    ----------
    n_records:
        Number of component records to simulate.
    seed:
        Random seed for full reproducibility.
    component_types:
        Restrict generation to a subset of component types.
    noise_level:
        Scales both observation noise and label noise. ``1.0`` is the tuned
        default; ``0`` produces an unrealistically clean, separable dataset.
    include_latent:
        When True, retain the hidden ``latent_degradation`` column. It is for
        analysis only and must never be used as a model feature.
    """
    if n_records <= 0:
        raise ValueError("n_records must be a positive integer")
    if noise_level < 0:
        raise ValueError("noise_level must be >= 0")

    rng = np.random.default_rng(seed)

    types = component_types or list(TYPE_WEIGHTS)
    unknown = set(types) - set(ComponentType.values())
    if unknown:
        raise ValueError(f"Unknown component types requested: {sorted(unknown)}")

    weights = np.array([TYPE_WEIGHTS[t] for t in types], dtype=float)
    weights = weights / weights.sum()
    chosen_types = rng.choice(types, size=n_records, p=weights)

    records: List[Dict[str, object]] = []

    for component_type in chosen_types:
        ref = reference_for(component_type)
        material = _weighted_choice(rng, TYPE_MATERIALS[component_type], 1)[0]

        # -- hidden drivers -------------------------------------------------
        # Building traffic intensity (duty). Lognormal keeps it positive and
        # right-skewed: a few very busy installations, many average ones.
        duty = float(np.clip(rng.lognormal(mean=0.0, sigma=0.30), 0.35, 2.4))
        # Maintenance regime quality in [0, 1].
        maintenance_quality = float(np.clip(rng.beta(5.0, 2.2), 0.05, 1.0))
        # Environmental stress the model never observes directly.
        env_stress = float(np.clip(rng.beta(2.0, 5.0), 0.0, 1.0))

        # -- age -------------------------------------------------------------
        design_life = ref["design_life_years"]
        age = float(np.clip(rng.beta(2.0, 2.4) * design_life * 1.45, 0.2, 58.0))

        # -- usage accumulation ---------------------------------------------
        annual_hours = ref["design_hours"] / design_life
        annual_cycles = ref["design_cycles"] / design_life
        operating_hours = float(
            np.clip(age * annual_hours * duty * rng.normal(1.0, 0.10 * noise_level + 1e-9), 0, 250_000)
        )
        load_cycles = float(
            np.clip(age * annual_cycles * duty * rng.normal(1.0, 0.13 * noise_level + 1e-9), 0, 5_000_000)
        )
        average_load = float(
            np.clip(ref["rated_load"] * rng.normal(0.62, 0.16) * (0.75 + 0.35 * duty), 5, 5000)
        )

        # -- latent wear (the hidden true condition) -------------------------
        usage_ratio = operating_hours / ref["design_hours"]
        cycle_ratio = load_cycles / ref["design_cycles"]
        age_ratio = age / design_life
        load_stress = average_load / ref["rated_load"]

        wear = (
            0.34 * usage_ratio
            + 0.18 * cycle_ratio
            + 0.14 * age_ratio
            + 0.10 * load_stress
            + 0.13 * (1.0 - maintenance_quality)
            + 0.11 * env_stress
            + rng.normal(0.0, 0.055 * noise_level)
        )
        wear = float(np.clip(wear, 0.0, 1.35))

        # -- noisy observations of the latent wear ---------------------------
        vibration = float(
            np.clip(
                ref["vibration_limit"]
                * (0.22 + 0.95 * wear)
                * rng.lognormal(0.0, 0.17 * noise_level + 1e-9),
                0.05,
                25.0,
            )
        )
        ambient = rng.normal(26.0, 4.0)
        temp_rise = (ref["temp_limit"] - 28.0) * (0.20 + 0.62 * wear) * (0.7 + 0.5 * load_stress)
        temperature = float(np.clip(ambient + temp_rise + rng.normal(0.0, 4.0 * noise_level), -10, 150))

        inspection_score = float(
            np.clip(100.0 - 78.0 * wear + rng.normal(0.0, 7.5 * noise_level), 0.0, 100.0)
        )

        service_count = int(
            np.clip(rng.poisson(max(age * 2.0 * maintenance_quality, 0.05)), 0, 200)
        )
        repair_count = int(
            np.clip(rng.poisson(max(age * 0.10 * (0.35 + 2.1 * wear), 0.01)), 0, 60)
        )
        failure_history = int(
            np.clip(rng.poisson(max(repair_count * 0.40 + wear * 0.55, 0.01)), 0, 40)
        )

        mean_gap = 190.0 / max(maintenance_quality, 0.15)
        days_since_last_service = int(
            np.clip(rng.exponential(mean_gap) * rng.normal(1.0, 0.2 * noise_level + 1e-9), 1, 4000)
        )
        # A component cannot have been serviced before it was installed.
        days_since_last_service = int(min(days_since_last_service, max(age * 365.25, 1)))

        label = _label_from_wear(wear, component_type, material)

        records.append(
            {
                "component_type": component_type,
                "material": material,
                "component_age": round(age, 2),
                "operating_hours": round(operating_hours, 1),
                "load_cycles": int(load_cycles),
                "average_load": round(average_load, 1),
                "vibration": round(vibration, 3),
                "temperature": round(temperature, 1),
                "service_count": service_count,
                "repair_count": repair_count,
                "failure_history": failure_history,
                "inspection_score": round(inspection_score, 1),
                "days_since_last_service": days_since_last_service,
                "latent_degradation": round(wear, 4),
                TARGET_COLUMN: label,
            }
        )

    frame = pd.DataFrame.from_records(records)

    # Adjacent-class label noise keeps the task realistically hard.
    frame[TARGET_COLUMN] = _apply_label_noise(
        rng,
        frame[TARGET_COLUMN].to_numpy(),
        0.055 * noise_level,
        frame["component_type"].to_numpy(),
        frame["material"].to_numpy(),
    )

    columns = FEATURE_COLUMNS + ([("latent_degradation")] if include_latent else []) + [TARGET_COLUMN]
    return frame[columns].reset_index(drop=True)


# --------------------------------------------------------------------------
# Survival dataset (P2 - forecasting)
# --------------------------------------------------------------------------
#: Columns emitted only by the survival generator, never model features.
SURVIVAL_COLUMNS = ["duration_years", "event_observed", "true_remaining_years", "followup_years"]

#: How long each component has been tracked since its observation point.
#: Drawn per component, this is what creates genuine right-censoring: a
#: component whose threshold crossing falls beyond its follow-up window is
#: recorded as "still healthy at F years", not as a missing outcome.
FOLLOWUP_MIN_YEARS = 0.5
FOLLOWUP_MAX_YEARS = 6.0


def _wear_trajectory(
    component_type: str,
    material: str,
    duty: float,
    maintenance_quality: float,
    env_stress: float,
    load_stress: float,
    hours_noise: float,
    cycles_noise: float,
    wear_noise: float,
) -> tuple[float, float, float]:
    """Return (slope, intercept, threshold) of the latent wear path in age.

    The generator's wear function is **linear in age** once the per-component
    latent draws are fixed:

        wear(t) = [0.34·duty·n1 + 0.18·duty·n2 + 0.14]/L · t
                  + [0.10·load_stress + 0.13·(1-mq) + 0.11·env + noise]

    because operating hours and load cycles both accumulate linearly with age
    at a rate set by duty. That means the age at which a component crosses the
    "no longer suitable for its current application" threshold has a closed
    form - no time-stepping loop, and no
    simulation noise in the event time itself.

    The returned threshold already has the disposition-policy offsets applied,
    so "crossing" means exactly where ``_label_from_wear`` stops returning
    CONTINUE_USING.
    """
    ref = reference_for(component_type)
    design_life = ref["design_life_years"]

    slope = (0.34 * duty * hours_noise + 0.18 * duty * cycles_noise + 0.14) / design_life
    intercept = (
        0.10 * load_stress + 0.13 * (1.0 - maintenance_quality) + 0.11 * env_stress + wear_noise
    )

    # Mirror the policy offsets in _effective_wear, moved onto the threshold.
    threshold = WEAR_THRESHOLDS[0]
    if component_type in SAFETY_CRITICAL:
        threshold -= SAFETY_STRICTNESS
    if component_type in STRUCTURAL:
        threshold -= STRUCTURAL_LENIENCY

    return slope, intercept, threshold


def generate_survival_dataset(
    n_records: int = 10_000,
    seed: int = 42,
    component_types: Optional[List[str]] = None,
    noise_level: float = 1.0,
) -> pd.DataFrame:
    """Time-to-event dataset for the end-of-life forecaster.

    Each row is one component **observed at a point while still suitable
    for its current application** (below the first wear threshold), with:

    * the same observable features the classifier sees, evaluated at that
      observation age,
    * ``duration_years`` - time from observation until either the threshold
      crossing or the end of its follow-up window, whichever comes first,
    * ``event_observed`` - 1 if the crossing was actually seen, 0 if the
      component was still healthy when observation stopped (right-censored).

    The crossing time derives from latent variables (duty, maintenance
    quality, environmental stress) that the model never sees, exactly as the
    classifier's label does - so there is no target leakage here either.
    """
    if n_records <= 0:
        raise ValueError("n_records must be a positive integer")
    if noise_level < 0:
        raise ValueError("noise_level must be >= 0")

    rng = np.random.default_rng(seed)
    types = component_types or list(TYPE_WEIGHTS)
    unknown = set(types) - set(ComponentType.values())
    if unknown:
        raise ValueError(f"Unknown component types requested: {sorted(unknown)}")

    weights = np.array([TYPE_WEIGHTS[t] for t in types], dtype=float)
    weights = weights / weights.sum()

    records: List[Dict[str, object]] = []
    attempts = 0
    max_attempts = n_records * 20

    while len(records) < n_records and attempts < max_attempts:
        attempts += 1
        component_type = str(rng.choice(types, p=weights))
        ref = reference_for(component_type)
        material = _weighted_choice(rng, TYPE_MATERIALS[component_type], 1)[0]

        duty = float(np.clip(rng.lognormal(mean=0.0, sigma=0.30), 0.35, 2.4))
        maintenance_quality = float(np.clip(rng.beta(5.0, 2.2), 0.05, 1.0))
        env_stress = float(np.clip(rng.beta(2.0, 5.0), 0.0, 1.0))
        load_stress_draw = float(rng.normal(0.62, 0.16) * (0.75 + 0.35 * duty))
        average_load = float(np.clip(ref["rated_load"] * load_stress_draw, 5, 5000))
        load_stress = average_load / ref["rated_load"]

        hours_noise = float(rng.normal(1.0, 0.10 * noise_level + 1e-9))
        cycles_noise = float(rng.normal(1.0, 0.13 * noise_level + 1e-9))
        wear_noise = float(rng.normal(0.0, 0.055 * noise_level))

        slope, intercept, threshold = _wear_trajectory(
            component_type, material, duty, maintenance_quality, env_stress,
            load_stress, hours_noise, cycles_noise, wear_noise,
        )
        if slope <= 0:  # pragma: no cover - defensive; duty and the 0.14 term keep it positive
            continue

        crossing_age = (threshold - intercept) / slope
        # Already past the threshold at installation, or implausibly long-lived:
        # neither is a component you would forecast, so redraw.
        if crossing_age <= 0.4 or crossing_age > 70.0:
            continue

        # Observe it at some point while it is still healthy.
        observation_age = float(rng.uniform(0.2, crossing_age))
        wear_now = float(np.clip(slope * observation_age + intercept, 0.0, 1.35))

        annual_hours = ref["design_hours"] / ref["design_life_years"]
        annual_cycles = ref["design_cycles"] / ref["design_life_years"]
        operating_hours = float(
            np.clip(observation_age * annual_hours * duty * hours_noise, 0, 250_000)
        )
        load_cycles = float(
            np.clip(observation_age * annual_cycles * duty * cycles_noise, 0, 5_000_000)
        )

        vibration = float(
            np.clip(
                ref["vibration_limit"] * (0.22 + 0.95 * wear_now)
                * rng.lognormal(0.0, 0.17 * noise_level + 1e-9),
                0.05, 25.0,
            )
        )
        ambient = rng.normal(26.0, 4.0)
        temp_rise = (ref["temp_limit"] - 28.0) * (0.20 + 0.62 * wear_now) * (0.7 + 0.5 * load_stress)
        temperature = float(np.clip(ambient + temp_rise + rng.normal(0.0, 4.0 * noise_level), -10, 150))
        inspection_score = float(
            np.clip(100.0 - 78.0 * wear_now + rng.normal(0.0, 7.5 * noise_level), 0.0, 100.0)
        )
        service_count = int(
            np.clip(rng.poisson(max(observation_age * 2.0 * maintenance_quality, 0.05)), 0, 200)
        )
        repair_count = int(
            np.clip(rng.poisson(max(observation_age * 0.10 * (0.35 + 2.1 * wear_now), 0.01)), 0, 60)
        )
        failure_history = int(
            np.clip(rng.poisson(max(repair_count * 0.40 + wear_now * 0.55, 0.01)), 0, 40)
        )
        mean_gap = 190.0 / max(maintenance_quality, 0.15)
        days_since_last_service = int(
            np.clip(rng.exponential(mean_gap) * rng.normal(1.0, 0.2 * noise_level + 1e-9), 1, 4000)
        )
        days_since_last_service = int(min(days_since_last_service, max(observation_age * 365.25, 1)))

        remaining = crossing_age - observation_age
        followup = float(rng.uniform(FOLLOWUP_MIN_YEARS, FOLLOWUP_MAX_YEARS))
        event_observed = int(remaining <= followup)
        duration = float(min(remaining, followup))

        records.append(
            {
                "component_type": component_type,
                "material": material,
                "component_age": round(observation_age, 2),
                "operating_hours": round(operating_hours, 1),
                "load_cycles": int(load_cycles),
                "average_load": round(average_load, 1),
                "vibration": round(vibration, 3),
                "temperature": round(temperature, 1),
                "service_count": service_count,
                "repair_count": repair_count,
                "failure_history": failure_history,
                "inspection_score": round(inspection_score, 1),
                "days_since_last_service": days_since_last_service,
                "duration_years": round(duration, 4),
                "event_observed": event_observed,
                "true_remaining_years": round(remaining, 4),
                "followup_years": round(followup, 4),
            }
        )

    if len(records) < n_records:  # pragma: no cover - only on pathological parameters
        raise RuntimeError(
            f"Only generated {len(records)} of {n_records} survival records in "
            f"{attempts} attempts - check the wear parameters"
        )

    return pd.DataFrame.from_records(records)[FEATURE_COLUMNS + SURVIVAL_COLUMNS].reset_index(drop=True)


def summarise_survival(frame: pd.DataFrame) -> str:
    """Human-readable summary of a generated survival dataset."""
    events = int(frame["event_observed"].sum())
    n = len(frame)
    observed = frame.loc[frame["event_observed"] == 1, "duration_years"]
    return "\n".join(
        [
            f"Records            : {n:,}",
            f"Events observed    : {events:,}  ({100.0 * events / max(n, 1):5.1f}%)",
            f"Right-censored     : {n - events:,}  ({100.0 * (n - events) / max(n, 1):5.1f}%)",
            f"Median time to event (observed only): {observed.median():.2f} years"
            if events
            else "Median time to event: n/a (no events)",
            f"True remaining life: median {frame['true_remaining_years'].median():.2f} years, "
            f"p90 {frame['true_remaining_years'].quantile(0.9):.2f} years",
        ]
    )


def summarise(frame: pd.DataFrame) -> str:
    """Return a human-readable summary of a generated dataset."""
    counts = frame[TARGET_COLUMN].value_counts()
    lines = [
        f"Records            : {len(frame):,}",
        f"Features           : {len(FEATURE_COLUMNS)}",
        f"Component types    : {frame['component_type'].nunique()}",
        f"Materials          : {frame['material'].nunique()}",
        "Class distribution :",
    ]
    for label in _ORDER:
        count = int(counts.get(label, 0))
        lines.append(f"    {label:<18} {count:>7,}  ({100.0 * count / len(frame):5.1f}%)")
    return "\n".join(lines)


def save_dataset(
    frame: pd.DataFrame,
    path: Path,
    split: bool = True,
    test_size: float = 0.2,
    seed: int = 42,
) -> Dict[str, Path]:
    """Persist the dataset (and optional stratified train/test split) as CSV."""
    path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(path, index=False)
    written = {"dataset": path}

    if split:
        from sklearn.model_selection import train_test_split

        train_df, test_df = train_test_split(
            frame, test_size=test_size, random_state=seed, stratify=frame[TARGET_COLUMN]
        )
        train_path = path.parent / "train.csv"
        test_path = path.parent / "test.csv"
        train_df.to_csv(train_path, index=False)
        test_df.to_csv(test_path, index=False)
        written["train"] = train_path
        written["test"] = test_path

    return written


